const FALLBACK_COLORS = [
  ['#0F766E', '#134E4A', '#5EEAD4'],
  ['#4338CA', '#312E81', '#A5B4FC'],
  ['#B45309', '#78350F', '#FDE68A'],
  ['#BE123C', '#881337', '#FDA4AF'],
  ['#334155', '#0F172A', '#CBD5E1'],
];

export function findCapeByName(name: string): MinecraftCapeDefinition | undefined {
  const normalized = name.trim().toLowerCase();
  if (!normalized) return undefined;
  return MINECRAFT_CAPES.find(
    (cape) =>
      cape.name.toLowerCase() === normalized ||
      cape.aliases?.some((a) => a.toLowerCase() === normalized)
  );
}

export function getCapeImageUrl(name: string): string {
  const known = findCapeByName(name);
  if (known) return known.imageUrl;

  let hash = 0;
  for (let i = 0; i < name.length; i++) {
    hash = (hash * 31 + name.charCodeAt(i)) >>> 0;
  }
  const [bg, border, accent] = FALLBACK_COLORS[hash % FALLBACK_COLORS.length];
  const { rows, palette } = solidBorderPattern(bg, border, [
    '........',
    '..xxxx..',
    '.x....x.',
    '.x.xx.x.',
    '.x.xx.x.',
    '.x....x.',
    '..xxxx..',
    '........',
    '........',
    '........',
    '........',
    '........',
    '........',
    '........',
  ]);
  return buildPixelCapeSvg(rows, { ...palette, x: accent });
}
