export interface MinecraftCapeDefinition {
  name: string;
  category:
    | 'MINECON'
    | 'Migration & Anniversary'
    | 'Event & Partner'
    | 'Mojang & Special'
    | 'Bedrock & Movie';
  aliases?: string[];
  imageUrl: string;
}

type Palette = Record<string, string>;

/**
 * Compiles a 10x16 pixel grid (16 rows of 10 chars) into a crisp pixel-art SVG data URI.
 */
function buildPixelCapeSvg(rows: string[], palette: Palette): string {
  const rects: string[] = [];
  for (let y = 0; y < rows.length; y++) {
    const row = rows[y];
    for (let x = 0; x < row.length; x++) {
      const ch = row[x];
      const fill = palette[ch];
      if (fill) {
        rects.push(`<rect x="${x}" y="${y}" width="1" height="1" fill="${fill}"/>`);
      }
    }
  }
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 10 16" shape-rendering="crispEdges">${rects.join('')}</svg>`;
  return `data:image/svg+xml;utf8,${encodeURIComponent(svg)}`;
}

function solidBorderPattern(bg: string, border: string, innerRows: string[]): { rows: string[]; palette: Palette } {
  const rows = [
    'bbbbbbbbbb',
    ...innerRows.map((r) => `b${r}b`),
    'bbbbbbbbbb',
  ];
  return {
    rows,
    palette: { '.': bg, b: border },
  };
}

function makeCape(
  name: string,
  category: MinecraftCapeDefinition['category'],
  rows: string[],
  palette: Palette,
  aliases?: string[]
): MinecraftCapeDefinition {
  return {
    name,
    category,
    aliases,
    imageUrl: buildPixelCapeSvg(rows, palette),
  };
}

